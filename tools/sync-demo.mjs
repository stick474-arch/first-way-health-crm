// Regenerates demo/index.html from index.html: same app, fictional data, no Supabase.
// Run after changing index.html:  node tools/sync-demo.mjs
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
let html = await readFile(`${root}index.html`, 'utf8');

html = html
  .replace('<title>Aetherium · CRM & Board</title>', '<title>Demo · Aetherium CRM & Board</title>')
  .replace(/(href|src)="(css|js)\//g, '$1="../$2/')
  .replace(/ *<!-- Production entry[^\n]*-->\n/, '')
  .replace('<script src="../js/config.js"></script>',
    '<script>window.FWH_CONFIG = { demo: true }; /* demo: fictional data in this browser, never Supabase */</script>')
  .replace('<!doctype html>', '<!doctype html>\n<!-- GENERATED by tools/sync-demo.mjs from index.html. Edit index.html, then re-run the script. -->');

if (!html.includes('FWH_CONFIG = { demo: true }')) throw new Error('Could not find js/config.js in index.html');
await mkdir(`${root}demo`, { recursive: true });
await writeFile(`${root}demo/index.html`, html);
console.log('demo/index.html updated');
