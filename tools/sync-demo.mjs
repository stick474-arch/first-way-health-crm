// Stamps a version on every stylesheet/script in index.html (so browsers never keep running an
// old copy after a deploy) and regenerates demo/index.html from it: same app, fictional data, no Supabase.
// Run after any change, before committing:  node tools/sync-demo.mjs
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const d = new Date();
const pad = (n) => String(n).padStart(2, '0');
const version = `${d.getFullYear()}${pad(d.getMonth() + 1)}${pad(d.getDate())}${pad(d.getHours())}${pad(d.getMinutes())}`;
const stamp = (html) => html.replace(/((?:href|src)="(?:\.\.\/)?(?:css|js)\/[^"?]+)(?:\?v=[^"]*)?"/g, `$1?v=${version}"`);

let html = stamp(await readFile(`${root}index.html`, 'utf8'));
await writeFile(`${root}index.html`, html);
await writeFile(`${root}recover.html`, stamp(await readFile(`${root}recover.html`, 'utf8')));

html = html
  .replace('<title>Aetherium · CRM & Board</title>', '<title>Demo · Aetherium CRM & Board</title>')
  .replace(/(href|src)="(css|js)\//g, '$1="../$2/')
  .replace(/ *<!-- Production entry[^\n]*-->\n/, '')
  .replace(new RegExp(`<script src="\\.\\./js/config\\.js\\?v=${version}"></script>`),
    '<script>window.FWH_CONFIG = { demo: true }; /* demo: fictional data in this browser, never Supabase */</script>')
  .replace('<!doctype html>', '<!doctype html>\n<!-- GENERATED by tools/sync-demo.mjs from index.html. Edit index.html, then re-run the script. -->');

if (!html.includes('FWH_CONFIG = { demo: true }')) throw new Error('Could not find js/config.js in index.html');
await mkdir(`${root}demo`, { recursive: true });
await writeFile(`${root}demo/index.html`, html);
console.log(`index.html, recover.html and demo/index.html stamped v=${version}`);
